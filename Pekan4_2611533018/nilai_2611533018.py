# Buat program untuk nested if
# Nama variabel ditambah 4 digit nim terakhir contoh: ipk_1234
# Pogram ini menggunakan fungsi input ()
# Program konversi nilai angka menjadi huruf

nilai_3018 = int(input("Masukkan nilai angka: "))

if nilai_3018 >= 81:
    print("A")
elif nilai_3018 >= 70:
    print("B")
elif nilai_3018 >= 60:
    print("C")
elif nilai_3018 >= 50:
    print("D")
else:
    print("E")