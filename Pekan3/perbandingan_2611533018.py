# Buat file dengan nama perbandingan_2611533018.py
# Nama variabel ditambah 4 digit nim terakhir contoh: angka_3018
# Program ini menggunakan fungsi input ()
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# Program operator perbandingan dalam Python

angka1_3018 = int(input("Masukkan angka-1: "))
angka2_3018 = int(input("Masukkan angka-2: "))

# Lebih besar dari
hasil_lebihbesar_3018 = angka1_3018 > angka2_3018
print("\nOperator lebih besar dari")
print("angka1 > angka2 =", hasil_lebihbesar_3018)

# Lebih kecil dari
hasil_lebihkecil_3018 = angka1_3018 < angka2_3018
print("\nOperator lebih kecil dari")
print("angka1 < angka2 =", hasil_lebihkecil_3018)

# Lebih besar atau sama dengan
hasil_lebihbesarsama_3018 = angka1_3018 >= angka2_3018
print("\nOperator lebih besar dari atau sama dengan")
print("angka1 >= angka2 =", hasil_lebihbesarsama_3018)

# Lebih kecil atau sama dengan
hasil_lebihkecilsama_3018 = angka1_3018 <= angka2_3018
print("\nOperator lebih kecil dari atau sama dengan")
print("angka1 <= angka2 =", hasil_lebihkecilsama_3018)

# Sama dengan
hasil_samadengan_3018 = angka1_3018 == angka2_3018
print("\nOperator sama dengan")
print("angka1 == angka2 =", hasil_samadengan_3018)

# Tidak sama dengan
hasil_tidaksama_3018 = angka1_3018 != angka2_3018
print("\nOperator tidak sama dengan")
print("angka1 != angka2 =", hasil_tidaksama_3018)

# Tambahan : perbandingan berantai dalam python
hasil_perbandingan_berantai_angka1_3018 = 0 < angka1_3018 < 100
print("\nPerbandingan berantai")
print("0 < angka1 < 100 =", hasil_perbandingan_berantai_angka1_3018)

hasil_perbandingan_berantai_angka2_3018 = 0 < angka2_3018 < 100
print("0 < angka2 < 100 =", hasil_perbandingan_berantai_angka2_3018)